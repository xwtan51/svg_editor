import type { FileMeasure } from "./FileMeasure.js";
import { FinalMapping } from "./FinalMapping.js";
import { SourceSnapshot } from "./SourceSnapshot.js";

/** A sum over some files. */
interface Totals {
  files: number;
  lines: number;
  codeLines: number;
  functions: number;
  complexity: number;
}

/** One row of the lines-by-area table. */
interface AreaRow {
  area: string;
  files: number;
  lines: number;
  codeLines: number;
  functions: number | null;
  complexity: number | null;
}

/**
 * The metrics of one revision `R` against `final` (design §5.3), rendered as
 * Markdown and as JSON. The output depends on the two commits only: no
 * time, no duration, no temporary path, no machine name; every list is
 * sorted by path in UTF-16 code-unit order.
 *
 * Areas of `R`, by path prefix: kernel `packages/kernel/src/`, host `src/`,
 * plugin `plugins/<directory>/src/` (built-in when the directory name starts
 * with `builtin-`, design §1.1), tests (`tests/`, `packages/*\/tests/`,
 * `plugins/*\/tests/`), scripts (`scripts/`), and `vscode-svg/` (src and
 * tests), which is reported separately and never added to a CLI total.
 * Complexity is reported for run code (kernel, host, plugins) and for
 * `vscode-svg/src/`; tests and scripts only count lines.
 */
export class MetricsReport {
  static readonly MARKDOWN = "metrics.md";
  static readonly JSON = "metrics.json";

  private static readonly KERNEL = "kernel";
  private static readonly HOST = "host";
  private static readonly BUILTIN = "plugins: built-in";
  private static readonly OPTIONAL = "plugins: optional";
  private static readonly DELETED = "deleted since final";
  private static readonly CATEGORIES = [MetricsReport.KERNEL, MetricsReport.HOST, MetricsReport.BUILTIN, MetricsReport.OPTIONAL];
  private static readonly PLUGIN_SOURCE = /^plugins\/([^/]+)\/src\//;
  private static readonly TEST_DIR = /^((?:packages|plugins)\/[^/]+\/tests\/|tests\/)/;
  private static readonly BUILTIN_PREFIX = "builtin-";

  private readonly revision: { commit: string; subject: string };
  private readonly finalCommit: string;
  private readonly run: readonly FileMeasure[];
  private readonly tests: readonly FileMeasure[];
  private readonly scripts: readonly FileMeasure[];
  private readonly vscodeSource: readonly FileMeasure[];
  private readonly vscodeTests: readonly FileMeasure[];
  private readonly final: readonly FileMeasure[];
  private readonly mapping: FinalMapping;

  /**
   * `measures`: every measured `.ts` file of `R` (run code, tests, scripts,
   * vscode-svg); `final`: the files of `final`'s `src/`.
   */
  constructor(revision: { commit: string; subject: string }, finalCommit: string, measures: readonly FileMeasure[], final: readonly FileMeasure[], mapping: FinalMapping) {
    const sorted = [...measures].sort((a, b) => SourceSnapshot.byCodeUnits(a.path, b.path));
    this.revision = revision;
    this.finalCommit = finalCommit;
    this.run = sorted.filter((file) => MetricsReport.categoryOf(file.path) !== null);
    this.tests = sorted.filter((file) => MetricsReport.TEST_DIR.test(file.path));
    this.scripts = sorted.filter((file) => file.path.startsWith("scripts/"));
    this.vscodeSource = sorted.filter((file) => file.path.startsWith("vscode-svg/src/"));
    this.vscodeTests = sorted.filter((file) => file.path.startsWith("vscode-svg/tests/"));
    this.final = [...final].sort((a, b) => SourceSnapshot.byCodeUnits(a.path, b.path));
    this.mapping = mapping;
  }

  /** Which files of `R` are run code, i.e. measured for complexity and mapped from `final`. */
  static isRunCode(file: string): boolean {
    return MetricsReport.categoryOf(file) !== null;
  }

  /** Which files of `R` the report reads: run code, tests, scripts and vscode-svg's src and tests. */
  static isMeasured(file: string): boolean {
    return (
      MetricsReport.isRunCode(file) ||
      MetricsReport.TEST_DIR.test(file) ||
      file.startsWith("scripts/") ||
      file.startsWith("vscode-svg/src/") ||
      file.startsWith("vscode-svg/tests/")
    );
  }

  markdown(): string {
    const out: string[] = [];
    const rCommit = this.revision.commit;
    out.push("# Metrics");
    out.push("");
    out.push("Generated by `npm run metrics` (`scripts/metrics/`, design §5.3) from git history only. Do not edit by hand.");
    out.push("");
    out.push(MetricsReport.table(["Revision", "Commit"], [["R", `\`${rCommit}\` ${MetricsReport.cell(this.revision.subject)}`], ["final", `\`${this.finalCommit}\``]]));
    out.push("");
    out.push(`Reproduce: \`npm run metrics -- ${rCommit}\`, then \`git diff --exit-code docs/metrics\` prints nothing.`);
    out.push("");
    out.push(
      "Cyclomatic complexity (decision X18): every function declaration or expression, method, constructor, accessor and arrow function is one function, " +
        "counted on its own (a nested function adds nothing to the one around it); $M_f = 1 + d_f$, where each `if`, `for`, `for…in`, `for…of`, `while`, `do`, " +
        "`case` (not `default`), `catch`, `?:`, `&&`, `||`, `??`, `&&=`, `||=` and `??=` is one decision point (`?.` is not); a file's $M$ is the sum over its functions. " +
        "Lines: physical lines; code lines leave out blank lines and lines holding only comments.",
    );
    out.push("");

    out.push("## 1. Run code by category, and the complexity increment since final");
    out.push("");
    out.push(MetricsReport.table(["Category", "Files", "Lines", "Code lines", "Functions", "M (R)", "Files in final", "M (final)", "ΔM"], this.categoryRows().map((row) => this.categoryCells(row))));
    out.push("");

    out.push("## 2. Lines by area (R)");
    out.push("");
    out.push(MetricsReport.table(["Area", "Files", "Lines", "Code lines", "Functions", "M"], this.areaRows().map((row) => MetricsReport.areaCells(row))));
    out.push("");
    out.push("Tests and scripts are not measured for complexity (design §5.3).");
    out.push("");

    out.push("## 3. Files of R (run code)");
    out.push("");
    out.push(
      MetricsReport.table(
        ["Path", "Category", "Responsibility", "Lines", "Code lines", "Functions", "M", "max M_f"],
        this.run.map((file) => [
          `\`${file.path}\``,
          MetricsReport.categoryOf(file.path) ?? "",
          MetricsReport.cell(file.responsibility ?? "—"),
          ...MetricsReport.numbers(file.lines, file.codeLines, file.functions.length, file.complexity(), file.maxComplexity()),
        ]),
      ),
    );
    out.push("");

    out.push("## 4. Complexity per file, final → R");
    out.push("");
    out.push("A file of `final` is mapped to its path in R by `git diff --find-renames --name-status final R` (no pathspec), then by file name for files rewritten beyond the rename threshold (design §5.3).");
    out.push("");
    out.push(
      MetricsReport.table(
        ["Path in R", "Path in final", "Mapped", "M (final)", "M (R)", "ΔM"],
        this.comparisonRows().map((row) => [
          row.path === null ? "—" : `\`${row.path}\``,
          row.finalPath === null ? "—" : `\`${row.finalPath}\``,
          row.how,
          String(row.finalComplexity),
          String(row.complexity),
          MetricsReport.signed(row.complexity - row.finalComplexity),
        ]),
      ),
    );
    out.push("");

    out.push("## 5. vscode-svg (separate: not part of any CLI total)");
    out.push("");
    const vscodeRows = this.vscodeSource.map((file) => [
      `\`${file.path}\``,
      MetricsReport.cell(file.responsibility ?? "—"),
      ...MetricsReport.numbers(file.lines, file.codeLines, file.functions.length, file.complexity(), file.maxComplexity()),
    ]);
    const source = MetricsReport.totals(this.vscodeSource);
    const tests = MetricsReport.lineTotals(this.vscodeTests);
    vscodeRows.push([`**vscode-svg/src/: ${source.files} files**`, "", ...MetricsReport.numbers(source.lines, source.codeLines, source.functions, source.complexity), ""]);
    vscodeRows.push([`vscode-svg/tests/: ${tests.files} files (lines only)`, "", ...MetricsReport.numbers(tests.lines, tests.codeLines), "—", "—", ""]);
    out.push(MetricsReport.table(["Path", "Responsibility", "Lines", "Code lines", "Functions", "M", "max M_f"], vscodeRows));
    out.push("");
    return out.join("\n");
  }

  json(): string {
    const file = (measure: FileMeasure) => ({
      path: measure.path,
      responsibility: measure.responsibility,
      lines: measure.lines,
      codeLines: measure.codeLines,
      functions: measure.functions.length,
      complexity: measure.complexity(),
      maxComplexity: measure.maxComplexity(),
    });
    const finalByTarget = this.finalByTarget();
    const document = {
      generator: "npm run metrics (scripts/metrics, design §5.3)",
      revisions: { R: this.revision, final: { commit: this.finalCommit } },
      categories: this.categoryRows(),
      areas: this.areaRows(),
      files: this.run.map((measure) => {
        const origin = finalByTarget.get(measure.path);
        return {
          ...file(measure),
          category: MetricsReport.categoryOf(measure.path),
          final: origin === undefined ? null : { path: origin.path, mapped: this.mapping.how(origin.path), complexity: origin.complexity() },
        };
      }),
      final: this.final.map((measure) => ({
        ...file(measure),
        target: this.mapping.targetOf(measure.path),
        mapped: this.mapping.how(measure.path),
      })),
      vscodeSvg: {
        files: this.vscodeSource.map(file),
        source: MetricsReport.totals(this.vscodeSource),
        tests: MetricsReport.lineTotals(this.vscodeTests),
      },
    };
    return `${JSON.stringify(document, null, 2)}\n`;
  }

  /** kernel / host / plugins: built-in / plugins: optional, or null for a file that is not run code. */
  private static categoryOf(file: string): string | null {
    if (file.startsWith("packages/kernel/src/")) {
      return MetricsReport.KERNEL;
    }
    const plugin = MetricsReport.PLUGIN_SOURCE.exec(file)?.[1];
    if (plugin !== undefined) {
      return plugin.startsWith(MetricsReport.BUILTIN_PREFIX) ? MetricsReport.BUILTIN : MetricsReport.OPTIONAL;
    }
    return file.startsWith("src/") ? MetricsReport.HOST : null;
  }

  private finalByTarget(): Map<string, FileMeasure> {
    const byTarget = new Map<string, FileMeasure>();
    for (const measure of this.final) {
      const target = this.mapping.targetOf(measure.path);
      if (target !== null) byTarget.set(target, measure);
    }
    return byTarget;
  }

  private categoryRows(): ({ category: string } & Totals & { finalFiles: number; finalComplexity: number; delta: number })[] {
    const finalOf = (category: string | null) =>
      MetricsReport.totals(this.final.filter((measure) => MetricsReport.categoryOrDeleted(this.mapping.targetOf(measure.path)) === category));
    const rows = MetricsReport.CATEGORIES.map((category) => {
      const totals = MetricsReport.totals(this.run.filter((file) => MetricsReport.categoryOf(file.path) === category));
      const before = finalOf(category);
      return { category, ...totals, finalFiles: before.files, finalComplexity: before.complexity, delta: totals.complexity - before.complexity };
    });
    const deleted = finalOf(MetricsReport.DELETED);
    rows.push({ category: MetricsReport.DELETED, ...MetricsReport.totals([]), finalFiles: deleted.files, finalComplexity: deleted.complexity, delta: -deleted.complexity });
    const all = MetricsReport.totals(this.run);
    const before = MetricsReport.totals(this.final);
    rows.push({ category: "total", ...all, finalFiles: before.files, finalComplexity: before.complexity, delta: all.complexity - before.complexity });
    return rows;
  }

  private categoryCells(row: ReturnType<MetricsReport["categoryRows"]>[number]): string[] {
    const name = row.category === "total" ? "**total**" : row.category;
    return [name, ...MetricsReport.numbers(row.files, row.lines, row.codeLines, row.functions, row.complexity, row.finalFiles, row.finalComplexity), MetricsReport.signed(row.delta)];
  }

  private static categoryOrDeleted(target: string | null): string {
    return (target === null ? null : MetricsReport.categoryOf(target)) ?? MetricsReport.DELETED;
  }

  /** Lines per area; functions and complexity only where they are measured (run code), null elsewhere. */
  private areaRows(): AreaRow[] {
    const rows: AreaRow[] = [];
    const add = (area: string, files: readonly FileMeasure[], complexityMeasured: boolean) => {
      const totals = MetricsReport.totals(files);
      rows.push(complexityMeasured ? { area, ...totals } : { area, ...MetricsReport.lineTotals(files), functions: null, complexity: null });
    };
    add("kernel `packages/kernel/src/`", this.run.filter((file) => MetricsReport.categoryOf(file.path) === MetricsReport.KERNEL), true);
    add("host `src/`", this.run.filter((file) => MetricsReport.categoryOf(file.path) === MetricsReport.HOST), true);
    for (const category of [MetricsReport.BUILTIN, MetricsReport.OPTIONAL]) {
      const files = this.run.filter((file) => MetricsReport.categoryOf(file.path) === category);
      for (const plugin of MetricsReport.distinct(files.map((file) => MetricsReport.PLUGIN_SOURCE.exec(file.path)?.[1] ?? ""))) {
        add(`plugin \`plugins/${plugin}/src/\``, files.filter((file) => file.path.startsWith(`plugins/${plugin}/src/`)), true);
      }
      add(`${category}: subtotal`, files, true);
    }
    add("**run code: total**", this.run, true);
    for (const dir of MetricsReport.distinct(this.tests.map((file) => MetricsReport.TEST_DIR.exec(file.path)?.[1] ?? ""))) {
      add(`tests \`${dir}\``, this.tests.filter((file) => file.path.startsWith(dir)), false);
    }
    add("tests: subtotal", this.tests, false);
    add("scripts `scripts/`", this.scripts, false);
    add("**CLI total** (run code, tests, scripts)", [...this.run, ...this.tests, ...this.scripts], false);
    return rows;
  }

  private static areaCells(row: AreaRow): string[] {
    return [row.area, ...MetricsReport.numbers(row.files, row.lines, row.codeLines), row.functions === null ? "—" : String(row.functions), row.complexity === null ? "—" : String(row.complexity)];
  }

  private comparisonRows(): { path: string | null; finalPath: string | null; how: string; finalComplexity: number; complexity: number }[] {
    const finalByTarget = this.finalByTarget();
    const rows: { path: string | null; finalPath: string | null; how: string; finalComplexity: number; complexity: number }[] = this.run.map((measure) => {
      const origin = finalByTarget.get(measure.path);
      return {
        path: measure.path,
        finalPath: origin?.path ?? null,
        how: origin === undefined ? "new" : this.mapping.how(origin.path),
        finalComplexity: origin?.complexity() ?? 0,
        complexity: measure.complexity(),
      };
    });
    for (const measure of this.final.filter((file) => this.mapping.targetOf(file.path) === null)) {
      rows.push({ path: null, finalPath: measure.path, how: FinalMapping.DELETED, finalComplexity: measure.complexity(), complexity: 0 });
    }
    return rows;
  }

  private static totals(files: readonly FileMeasure[]): Totals {
    return {
      files: files.length,
      lines: files.reduce((sum, file) => sum + file.lines, 0),
      codeLines: files.reduce((sum, file) => sum + file.codeLines, 0),
      functions: files.reduce((sum, file) => sum + file.functions.length, 0),
      complexity: files.reduce((sum, file) => sum + file.complexity(), 0),
    };
  }

  private static lineTotals(files: readonly FileMeasure[]): { files: number; lines: number; codeLines: number } {
    const { files: count, lines, codeLines } = MetricsReport.totals(files);
    return { files: count, lines, codeLines };
  }

  private static distinct(values: readonly string[]): string[] {
    return [...new Set(values)].sort(SourceSnapshot.byCodeUnits);
  }

  private static numbers(...values: number[]): string[] {
    return values.map(String);
  }

  private static signed(value: number): string {
    return value > 0 ? `+${value}` : String(value);
  }

  /** Text for a table cell: `|` escaped. */
  private static cell(text: string): string {
    return text.replaceAll("|", "\\|");
  }

  private static table(header: readonly string[], rows: readonly (readonly string[])[]): string {
    const line = (cells: readonly string[]) => `| ${cells.join(" | ")} |`;
    return [line(header), line(header.map(() => "---")), ...rows.map(line)].join("\n");
  }
}
